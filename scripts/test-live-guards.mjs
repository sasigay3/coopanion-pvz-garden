import assert from 'node:assert/strict';
import {missingNightCards,missingPoolCard,poolLanesMissingDamage,waterPadNeeded,nearbyCherryWaterCell,emptyPoolEconomyCells,poolEmergencyHint,wonAwardId} from '../src/live-guards.ts';
import {PvzExecutor} from '../src/executor.ts';
import {seedAllowedByPublicProgress} from '../src/unlocks.ts';
const choices=Array.from({length:12},(_,id)=>({id,name:String(id),state:'chooser',fixed:false}));
const picker={capacity:5,selected:[0,1,2,3,4],choices};
const base={screen:'seed_picker',modeKind:'adventure',modeName:'adventure',profile:{adventureLevel:15,adventureCompletions:0},seedPicker:picker};
assert.deepEqual(missingNightCards(base),['小喷菇','阳光菇']);
assert.equal(seedAllowedByPublicProgress(base.profile,40),true);
assert.equal(seedAllowedByPublicProgress(base.profile,39),false);
assert.deepEqual(missingNightCards({...base,profile:{...base.profile,adventureLevel:4}}),[]);
for (const modeName of ['survival_night','survival_fog','survival_hard_night','survival_endless_fog'])
  assert.deepEqual(missingNightCards({...base,modeKind:'survival',modeName}),[]);
assert.deepEqual(missingNightCards({...base,seedPicker:{...picker,selected:[8,9,2,3,4]}}),[]);
assert.deepEqual(missingNightCards({...base,seedPicker:{...picker,choices:choices.filter(c=>c.id!==9)}}),[]);
assert.deepEqual(missingNightCards({...base,seedPicker:{...picker,choices:choices.map(c=>({...c,fixed:c.id<4}))}}),[]);
const poolChoices=Array.from({length:20},(_,id)=>({id,name:String(id),state:'chooser',fixed:false}));
const poolPicker={capacity:5,selected:[0,1,2,3,4],choices:poolChoices};
const pool={...base,profile:{...base.profile,adventureLevel:21},seedPicker:poolPicker};
assert.deepEqual(missingPoolCard(pool),['荷叶']);
assert.deepEqual(missingPoolCard({...pool,seedPicker:{...poolPicker,selected:[0,1,2,3,16]}}),[]);
assert.deepEqual(missingPoolCard({...pool,profile:{...pool.profile,adventureLevel:20}}),[]);
assert.deepEqual(missingPoolCard({...pool,seedPicker:{...poolPicker,choices:poolChoices.map(c=>({...c,fixed:c.id<5}))}}),[]);
const poolBoard={runId:12,background:2,paused:false,disclosure:{entitiesVisible:true},fog:{active:false},special:null,tutorial:null,cells:[{row:3,terrain:'water'},{row:4,terrain:'water'}],plants:[]};
const poolSnapshot={screen:'board',modeKind:'adventure',board:poolBoard,lastRun:null};
assert.deepEqual(poolLanesMissingDamage(poolSnapshot),[3,4]);
assert.deepEqual(poolLanesMissingDamage({...poolSnapshot,board:{...poolBoard,plants:[{row:3,type:0,sleeping:false,squished:false}]}}),[4]);
assert.deepEqual(poolLanesMissingDamage({...poolSnapshot,board:{...poolBoard,plants:[{row:3,type:3,sleeping:false,squished:false}]}}),[3,4]);
assert.deepEqual(poolLanesMissingDamage({...poolSnapshot,board:{...poolBoard,fog:{active:true}}}),[]);
const water={row:3,column:1,terrain:'water',playable:true,base:'none',blocker:'requires_lily_pad'};
const safeBoard={...poolBoard,sun:200,cursor:{kind:'normal'},cells:[water],plants:[],zombies:[],cards:[{type:1},{type:16}]};
const sunflower={type:1,imitates:null,ready:true,cost:50},pad={type:16,imitates:null,ready:true,cost:25};
assert.equal(waterPadNeeded(safeBoard,3,1,sunflower,pad),true);
assert.equal(waterPadNeeded({...safeBoard,sun:74},3,1,sunflower,pad),false);
assert.equal(waterPadNeeded({...safeBoard,cursor:{kind:'usable_seed'}},3,1,sunflower,pad),false);
assert.equal(waterPadNeeded(safeBoard,3,1,{...sunflower,type:19},pad),false);
assert.deepEqual(emptyPoolEconomyCells({...poolSnapshot,board:safeBoard}),[{row:3,column:1}]);
assert.deepEqual(emptyPoolEconomyCells({...poolSnapshot,board:{...safeBoard,zombies:[{hypnotized:false,columnPosition:3}]}}),[]);
assert.deepEqual(emptyPoolEconomyCells({...poolSnapshot,board:{...safeBoard,plants:[{row:3,column:1,type:0}]}}),[]);
const target={row:3,column:5,terrain:'water',playable:true,base:'lily_pad',blocker:'occupied'};
const alternate={row:3,column:4,terrain:'water',playable:true,base:'lily_pad',blocker:null};
const battle={...safeBoard,cells:[target,alternate],zombies:[{row:3,columnPosition:4.8,hypnotized:false}]};
assert.equal(nearbyCherryWaterCell(battle,3,5),4);
assert.equal(nearbyCherryWaterCell({...battle,zombies:[{row:3,columnPosition:5.8,hypnotized:false}]},3,5),null);
const danger={...poolSnapshot,board:{...safeBoard,cards:[{type:2,ready:true,affordable:true}],cells:[{row:3,column:3,terrain:'water',playable:true,base:'lily_pad',blocker:null}],zombies:[{row:3,columnPosition:3.2,hypnotized:false}]}};
assert.deepEqual(poolEmergencyHint(danger),{row:3,column:3,threatRow:3});
assert.equal(poolEmergencyHint({...danger,board:{...danger.board,cards:[{type:2,ready:false,affordable:true}]}}),null);
assert.equal(poolEmergencyHint({...danger,board:{...danger.board,cells:[{...danger.board.cells[0],blocker:'occupied'}]}}),null);
const board={runId:42,paused:false,disclosure:{entitiesVisible:true},collectibles:[{id:7,kind:'seed_packet'}]};
const won={screen:'board',board,lastRun:{runId:42,outcome:'won'},executable:{supported:true},presentation:{managed:true,onScreen:true}};
assert.equal(wonAwardId(won),7);
assert.equal(wonAwardId({...won,lastRun:{runId:41,outcome:'won'}}),null);
assert.equal(wonAwardId({...won,lastRun:null}),null);
assert.equal(wonAwardId({...won,board:{...board,collectibles:[{id:8,kind:'usable_seed'}]}}),null);
assert.equal(wonAwardId({...won,presentation:{managed:true,onScreen:false}}),null);
let invoked=false;
const result=await new Promise((resolve,reject)=>{
  const timer=setTimeout(()=>reject(Error('自动奖励任务超时')),3000);
  const ex=new PvzExecutor({snapshot:()=>({...won,mode:0}),execute:async step=>{invoked=step.skill==='auto_award';return {outcome:'done',text:'已验证'}},cancelNative:async()=>{},report:()=>{},reportInternal:r=>{clearTimeout(timer);resolve(r)},nextId:()=>1});
  ex.submitInternal([{skill:'auto_award'}]);
});
assert.equal(invoked,true);
assert.equal(result.kind,'done');
console.log('夜晚必备卡及胜利奖励保护检查通过');
